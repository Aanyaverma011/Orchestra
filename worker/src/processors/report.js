const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const config = require('../config');
const { sleep, log, progress } = require('../lib');

const DEPARTMENTS = ['Engineering', 'Sales', 'Finance', 'HR', 'Operations', 'Support'];

// Small seeded PRNG so the same job always produces the same report.
function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 0xffffffff;
  };
}

function buildRows(count, seed) {
  const rand = rng(seed);
  return Array.from({ length: count }, (_, i) => {
    const present = Math.round(14 + rand() * 8);
    return {
      id: `EMP-${String(1000 + i)}`,
      department: DEPARTMENTS[Math.floor(rand() * DEPARTMENTS.length)],
      present,
      absent: 22 - present,
      pct: Math.round((present / 22) * 100),
    };
  });
}

function writePdf(file, title, rows, summary) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 48 });
    const out = fs.createWriteStream(file);
    out.on('finish', resolve).on('error', reject);
    doc.pipe(out);

    doc.fontSize(20).fillColor('#111827').text(title);
    doc.moveDown(0.3).fontSize(10).fillColor('#6B7280').text(`Generated by Orchestra on ${new Date().toUTCString()}`);
    doc.moveDown();
    doc.fontSize(12).fillColor('#111827');
    doc.text(`Employees: ${summary.employees}`);
    doc.text(`Average attendance: ${summary.avgPct}%`);
    doc.text(`Lowest attendance: ${summary.lowest.id} (${summary.lowest.pct}%)`);
    doc.moveDown();

    const cols = [60, 160, 110, 110, 70];
    const header = ['ID', 'Department', 'Present', 'Absent', '%'];
    const drawRow = (vals, bold) => {
      let x = doc.page.margins.left;
      const y = doc.y;
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10);
      vals.forEach((v, i) => {
        doc.text(String(v), x, y, { width: cols[i] });
        x += cols[i];
      });
      doc.moveDown(0.4);
    };
    drawRow(header, true);
    rows.slice(0, 40).forEach((r) => drawRow([r.id, r.department, r.present, r.absent, `${r.pct}%`]));
    if (rows.length > 40) doc.moveDown().font('Helvetica-Oblique').text(`... and ${rows.length - 40} more rows (see CSV export).`);
    doc.end();
  });
}

async function generateReport(job) {
  const { title = 'Attendance Report', employees = 500, format = 'pdf' } = job.data;
  const count = Math.max(1, Math.min(Number(employees) || 500, 50000));

  await log(job, 'info', `Fetching attendance data for ${count} employees`);
  await progress(job, 10);
  await sleep(config.simulateWorkMs);

  const rows = buildRows(count, count);
  const avgPct = Math.round(rows.reduce((a, r) => a + r.pct, 0) / rows.length);
  const lowest = rows.reduce((m, r) => (r.pct < m.pct ? r : m), rows[0]);
  await log(job, 'info', `Aggregated ${rows.length} rows, average attendance ${avgPct}%`);
  await progress(job, 55);
  await sleep(config.simulateWorkMs / 2);

  const dir = path.resolve(config.dataDir, 'reports');
  fs.mkdirSync(dir, { recursive: true });
  const ext = format === 'csv' ? 'csv' : 'pdf';
  const rel = path.join('reports', `${job.id}.${ext}`);
  const full = path.resolve(config.dataDir, rel);

  if (ext === 'csv') {
    const lines = ['id,department,present,absent,percent', ...rows.map((r) => `${r.id},${r.department},${r.present},${r.absent},${r.pct}`)];
    fs.writeFileSync(full, lines.join('\n'));
  } else {
    await writePdf(full, title, rows, { employees: rows.length, avgPct, lowest });
  }

  await progress(job, 100);
  const bytes = fs.statSync(full).size;
  await log(job, 'info', `Report saved (${ext.toUpperCase()}, ${bytes} bytes)`);
  return { file: rel, format: ext, rows: rows.length, avgAttendance: avgPct, bytes };
}

module.exports = { generateReport, buildRows };
